#!/usr/bin/env python3
"""Generate src/pinyin_data.inc from mozillazg/pinyin-data pinyin.txt.

Covers CJK Unified Ideographs U+4E00..U+9FFF with up to two toneless readings
per character (ü written as v). Usage:
  curl -LO https://raw.githubusercontent.com/mozillazg/pinyin-data/master/pinyin.txt
  python3 tools/gen_pinyin.py pinyin.txt > src/pinyin_data.inc
"""
import sys
import unicodedata

LO, HI = 0x4E00, 0x9FFF


def toneless(s):
    s = s.replace("ü", "v").replace("ǖ", "v").replace("ǘ", "v").replace("ǚ", "v").replace("ǜ", "v")
    s = "".join(c for c in unicodedata.normalize("NFD", s) if not unicodedata.combining(c))
    return s.replace("u\u0308", "v").lower()


def main():
    readings = {}
    for line in open(sys.argv[1], encoding="utf-8"):
        if not line.startswith("U+"):
            continue
        code, rest = line.split(":", 1)
        cp = int(code[2:], 16)
        if not LO <= cp <= HI:
            continue
        out = []
        for r in rest.split("#")[0].strip().split(","):
            t = toneless(r.strip())
            if t and t.isalpha() and t not in out:
                out.append(t)
        if out:
            readings[cp] = out[:2]

    syl = sorted({s for rs in readings.values() for s in rs})
    idx = {s: i + 1 for i, s in enumerate(syl)}  # 0 = none
    print("// Generated by tools/gen_pinyin.py from mozillazg/pinyin-data. Do not edit.")
    print("static const unsigned kPinyinLo = 0x%X, kPinyinHi = 0x%X;" % (LO, HI))
    print("static const char* const kSyllables[] = {\"\",")
    for i in range(0, len(syl), 12):
        print("  " + ", ".join('"%s"' % s for s in syl[i:i + 12]) + ",")
    print("};")
    for n in (0, 1):
        print("static const unsigned short kReading%d[] = {" % n)
        row = []
        for cp in range(LO, HI + 1):
            rs = readings.get(cp, [])
            row.append(str(idx[rs[n]]) if len(rs) > n else "0")
            if len(row) == 32:
                print("  " + ",".join(row) + ",")
                row = []
        if row:
            print("  " + ",".join(row) + ",")
        print("};")


if __name__ == "__main__":
    main()
